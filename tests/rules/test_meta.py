from __future__ import annotations

from typing import TYPE_CHECKING

import pytest

from smelt.engine.check import CheckOptions
from tests.helpers import violations, write_project

if TYPE_CHECKING:
    from pathlib import Path

CONFIG = "version: 2\nproject: {root_packages: [app], test_roots: [tests]}\n"
TOOL_REASON = CheckOptions(select=("MET006",))


def _project(root: Path, source: str, *, path: str = "app/api.py") -> None:
    write_project(root, {"smelt.yml": CONFIG, "app/__init__.py": "", path: source})


@pytest.mark.parametrize(
    ("comment", "directive"),
    [
        ("# noqa", "noqa"),
        ("# noqa: F403", "noqa"),
        ("# NOQA:E501,F401", "noqa"),
        ("# type: ignore", "type: ignore"),
        ("# type: ignore[arg-type]", "type: ignore"),
        ("# pyright: ignore", "pyright: ignore"),
        ("# pyright: ignore[reportAny]", "pyright: ignore"),
        ("# pylint: disable=broad-exception-caught", "pylint: disable"),
        ("# pylint: disable-next=invalid-name", "pylint: disable-next"),
    ],
)
def test_inline_tool_suppressions_without_reason_are_reported(
    tmp_path: Path, comment: str, directive: str
) -> None:
    _project(tmp_path, f"import os\nvalue = os.sep  {comment}\n")
    [finding] = violations(tmp_path, TOOL_REASON)
    assert (finding.code, finding.path, finding.line, finding.column) == (
        "MET006",
        "app/api.py",
        2,
        17,
    )
    assert finding.expected == {"directives": [directive], "automatic_rewrite": False}
    assert f"`{directive}`" in finding.message


@pytest.mark.parametrize(
    ("comment", "directive"),
    [
        ("# ruff: noqa", "ruff: noqa"),
        ("# ruff: noqa: F401", "ruff: noqa"),
        ("# flake8: noqa", "flake8: noqa"),
        ("# mypy: ignore-errors", "mypy: ignore-errors"),
        ("# mypy: disable-error-code=no-untyped-def", "mypy: disable-error-code"),
    ],
)
def test_file_level_directives_are_one_finding_on_their_line(
    tmp_path: Path, comment: str, directive: str
) -> None:
    _project(tmp_path, f'"""Adapters."""\n{comment}\nimport os\n')
    [finding] = violations(tmp_path, TOOL_REASON)
    assert (finding.line, finding.expected) == (
        2,
        {"directives": [directive], "automatic_rewrite": False},
    )


@pytest.mark.parametrize(
    "source",
    [
        "value = 1  # type: ignore[assignment] -- stub is wrong, see #123\n",
        "value = 1  # noqa: E501 - the URL cannot be wrapped\n",
        "value = 1  # pyright: ignore[reportAny]  # SDK returns Any\n",
        "# The SDK stub declares the wrong type, see #123.\nvalue = 1  # type: ignore\n",
        "# Generated client, regenerated by scripts/client.py.\n# ruff: noqa\nvalue = 1\n",
    ],
)
def test_reasons_inline_and_on_the_line_above_are_accepted(
    tmp_path: Path, source: str
) -> None:
    _project(tmp_path, source)
    assert violations(tmp_path, TOOL_REASON) == []


@pytest.mark.parametrize(
    "source",
    [
        "# noqa: E501\nvalue = 1  # type: ignore\n",
        "# reason\n\nvalue = 1  # type: ignore\n",
        "value = 1  # type: ignore  # noqa: E501\n",
    ],
)
def test_directives_and_detached_comments_are_no_reason(
    tmp_path: Path, source: str
) -> None:
    _project(tmp_path, source)
    lines = [v.line for v in violations(tmp_path, TOOL_REASON)]
    assert lines[-1] == source.count("\n")


@pytest.mark.parametrize(
    "source",
    [
        "value = 1  # pragma: no cover\n",
        "value = 1  # fmt: skip\n",
        "value = 1  # type: int\n",
        "# pyright: strict\nvalue = 1\n",
        "value = 1  # the noqa convention is documented elsewhere\n",
        'value = "# type: ignore"\n',
        "value = 1  # smelt: ignore[TYP001]\n",
    ],
)
def test_other_comments_and_strings_are_not_tool_suppressions(
    tmp_path: Path, source: str
) -> None:
    _project(tmp_path, source)
    assert violations(tmp_path, TOOL_REASON) == []


def test_test_modules_are_checked(tmp_path: Path) -> None:
    _project(
        tmp_path,
        "def test_fetch():\n    assert fetch()  # type: ignore[no-untyped-call]\n",
        path="tests/test_api.py",
    )
    [finding] = violations(tmp_path, TOOL_REASON)
    assert (finding.code, finding.path, finding.line, finding.source_module) == (
        "MET006",
        "tests/test_api.py",
        2,
        None,
    )


def test_opt_in_excluded_paths_and_unchanged_smelt_reason_rule(
    tmp_path: Path,
) -> None:
    _project(tmp_path, "value = 1  # type: ignore\n")
    assert violations(tmp_path) == []
    write_project(
        tmp_path,
        {
            "smelt.yml": CONFIG
            + "rules: {meta/missing-tool-suppression-reason: warning}\n",
        },
    )
    assert [v.code for v in violations(tmp_path)] == ["MET006"]
    write_project(
        tmp_path,
        {
            "smelt.yml": "version: 2\nproject:\n  root_packages: [app]\n"
            "  test_roots: [tests]\n  exclude:\n"
            "    - {path: app/api.py, reason: Generated client.}\n"
            "rules: {meta/missing-tool-suppression-reason: warning}\n",
        },
    )
    assert violations(tmp_path) == []


def test_smelt_suppression_reason_stays_with_met002(tmp_path: Path) -> None:
    _project(
        tmp_path,
        "from __future__ import annotations  # smelt: ignore[TYP001]\n",
    )
    found = violations(tmp_path, CheckOptions(select=("MET002", "MET006")))
    assert "MET006" not in {v.code for v in found}
